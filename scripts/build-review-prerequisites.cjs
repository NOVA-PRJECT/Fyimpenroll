const fs=require('node:fs'),path=require('node:path')
const directory=path.resolve(__dirname,'../supabase/changes')
const unwrap=text=>text.replace(/^BEGIN;\r?$/m,'').replace(/^COMMIT;\r?$/m,'')
let manual=fs.readFileSync(path.join(directory,'manual_timetable.sql'),'utf8')
const originalGuard=/DO \$\$ DECLARE definition text; BEGIN[\s\S]*?END \$\$;/
if(!originalGuard.test(manual))throw Error('Manual timetable guard changed; review prerequisite packaging')
manual=manual.replace(originalGuard,()=>`DO $$ DECLARE definition text; BEGIN
 SELECT pg_get_functiondef('public.mutate_teacher_assignments(uuid,text,jsonb,uuid,uuid,uuid)'::regprocedure) INTO definition;
 IF position('actor_role NOT IN (''superadmin'',''hod'',''campus_director'')' IN definition)>0 THEN
  definition:=replace(definition,'actor_role NOT IN (''superadmin'',''hod'',''campus_director'')','actor_role <> ''hod''');
  EXECUTE definition;
 ELSIF position('IF actor_role IS NULL OR actor_role <> ''hod'' THEN' IN definition)>0 THEN
  NULL; -- The same HOD-only restriction was already installed separately.
 ELSE
  RAISE EXCEPTION 'Unexpected teacher mutation definition; no prerequisite changes applied';
 END IF;
END $$;`)
const result=`-- Generated by node scripts/build-review-prerequisites.cjs. Do not edit this bundle directly.
-- OWNER-RUN ONLY: for lifecycle + display aggregation installed, manual + preference releases missing.
-- Rehearse on staging; pause application writes for the coordinated cutover.
-- Does not replay lifecycle SQL, invoke repair routines, or modify existing domain records.
BEGIN;
SET LOCAL lock_timeout='10s';
SELECT pg_advisory_xact_lock(76102622134917::bigint);
DO $$ DECLARE signature text; BEGIN
 IF to_regprocedure('public.application_schema_compatibility()') IS NOT NULL THEN
  RAISE EXCEPTION 'Review release is already installed; do not run the prerequisite bridge'; END IF;
 FOREACH signature IN ARRAY ARRAY[
  'public.campus_term_version(uuid)',
  'public.lock_campus_lifecycle_writes()',
  'public.mutate_teacher_assignments(uuid,text,jsonb,uuid,uuid,uuid)',
  'public.submit_student_registration(uuid,uuid,smallint,text,text,jsonb,jsonb,jsonb,numeric,timestamptz)',
  'public.apply_course_allocation(uuid,uuid,text,smallint,jsonb,jsonb,jsonb,uuid)',
  'public.display_enrollment_counts(jsonb)',
  'public.display_period_status(jsonb,date)'
 ] LOOP
  IF to_regprocedure(signature) IS NULL THEN
   RAISE EXCEPTION 'Missing bridge prerequisite: %. No changes applied; inspect schema without replaying lifecycle SQL.',signature;
  END IF;
 END LOOP;
 IF to_regprocedure('public.timetable_manual_context(uuid,text,integer,uuid,integer)') IS NOT NULL
  OR to_regprocedure('public.commit_manual_timetable(uuid,text,integer,uuid,integer,text,jsonb,boolean)') IS NOT NULL THEN
  RAISE EXCEPTION 'Manual timetable is installed or partially installed; this bridge requires both routines to be absent';
 END IF;
 IF to_regprocedure('public.guard_enrollment_allocation_completion()') IS NOT NULL
  OR EXISTS(SELECT 1 FROM pg_trigger WHERE tgrelid='public.student_registrations'::regclass AND tgname='enrollment_after_allocation') THEN
  RAISE EXCEPTION 'Preference release is installed or partially installed; inspect it before applying this bridge';
 END IF;
END $$;

-- Source: manual_timetable.sql. Only its known HOD-policy guard is made compatible with an already restricted routine.
${unwrap(manual)}

-- Source: preferences_before_allocation.sql. Defines the repair function without invoking it.
${unwrap(fs.readFileSync(path.join(directory,'preferences_before_allocation.sql'),'utf8'))}

COMMIT;
-- Expected: all four rows installed=true; review_release_installed remains false until review_release.sql is applied.
SELECT signature,to_regprocedure(signature) IS NOT NULL AS installed FROM (VALUES
 ('public.timetable_manual_context(uuid,text,integer,uuid,integer)'),
 ('public.display_enrollment_counts(jsonb)'),
 ('public.display_period_status(jsonb,date)'),
 ('public.guard_enrollment_allocation_completion()')
) AS prerequisites(signature);
`
const target=path.join(directory,'review_missing_prerequisites.sql')
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==result)throw Error('Prerequisite bundle is stale; run node scripts/build-review-prerequisites.cjs')
}else fs.writeFileSync(target,result)
